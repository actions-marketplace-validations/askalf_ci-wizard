// Bundles the action, the CLI and the library into dist/ with their one dependency (the yaml
// parser) inlined, so neither the action nor the npm package installs anything at run time.
// dist/ is committed: a GitHub Action runs from the repository as it is, with no install step.
// CI rebuilds and fails on any difference, so dist/ always matches src/.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const yamlPkg = JSON.parse(readFileSync('node_modules/yaml/package.json', 'utf8'));
const banner = `// ci-wizard. Generated by build.mjs from src/; do not edit. Bundles yaml ${yamlPkg.version} (ISC), see dist/THIRD_PARTY_LICENSES.txt.`;

await build({
  entryPoints: { action: 'src/action.mjs', cli: 'src/cli.mjs', index: 'src/index.mjs' },
  outdir: 'dist',
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  charset: 'utf8',
  // yaml's Node entry is CommonJS and requires node builtins; an ESM bundle needs a require for them.
  banner: { js: `${banner}
import { createRequire as __ciwCreateRequire } from 'node:module';
const require = __ciwCreateRequire(import.meta.url);` },
  logLevel: 'warning',
});

writeFileSync(
  'dist/THIRD_PARTY_LICENSES.txt',
  `yaml ${yamlPkg.version} (https://github.com/eemeli/yaml)\n\n${readFileSync('node_modules/yaml/LICENSE', 'utf8').replace(/\r\n/g, '\n')}`,
);
